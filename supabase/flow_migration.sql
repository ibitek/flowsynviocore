create or replace function public.reserve_ai_call(p_org uuid,p_actor uuid,p_ticket uuid,p_operation text,p_key text,p_fingerprint text,p_reserve bigint) returns jsonb
language plpgsql security definer set search_path='' as $$
declare w public.organization_wallets%rowtype;r public.ai_billing_requests%rowtype;s public.billing_subscriptions%rowtype;included bigint:=0;
begin
 if not exists(select 1 from public.organization_members where organization_id=p_org and user_id=p_actor and role in ('admin','agent')) then raise exception 'Membership required';end if;
 if p_ticket is not null and not exists(select 1 from public.tickets where id=p_ticket and organization_id=p_org) then raise exception 'Ticket unavailable';end if;
 if p_operation not in ('draft','employee_chat','attachment_inspection','inbox_setup_help','continuation_summary','context_summary','flow_chat','flow_builder') or (p_ticket is null and p_operation not in ('inbox_setup_help','flow_chat','flow_builder')) then raise exception 'Invalid operation';end if;
 if p_key is null or length(p_key) not between 8 and 160 or p_fingerprint is null or length(p_fingerprint)<>64 or p_reserve is null or p_reserve not between 1 and 150000 then raise exception 'Invalid reservation';end if;
 select * into w from public.organization_wallets where organization_id=p_org for update;
 if not found or w.balance_micro_usd<=0 or w.unlocked_at is null or w.metering_hold then raise exception 'Payment required';end if;
 select * into r from public.ai_billing_requests where organization_id=p_org and request_key=p_key;
 if found then
  if r.fingerprint<>p_fingerprint or r.actor_id<>p_actor or r.operation<>p_operation or r.ticket_id is distinct from p_ticket then raise exception 'Idempotency key mismatch';end if;
  return to_jsonb(r)||jsonb_build_object('claimed',false);
 end if;
 select * into s from public.billing_subscriptions where organization_id=p_org and starts_at<=now() order by starts_at desc limit 1 for update;
 if found then
  if s.ends_at<=now() and not s.overage_enabled then raise exception 'Plan expired. Renew or explicitly enable PAYG';end if;
  if s.ends_at<=now() then s.remaining_micro_usd:=0;end if;
  if not (p_actor=any(s.seat_ids)) and not exists(select 1 from public.organization_members where organization_id=p_org and user_id=p_actor and role='admin') then
   if not s.overage_enabled then raise exception 'This employee is not covered by the active plan. Enable PAYG or renew with updated seats';end if;
  else included:=least(s.remaining_micro_usd,p_reserve);end if;
  if included<p_reserve and not s.overage_enabled then raise exception 'Plan allowance cannot cover this action. AI paused; admin can explicitly enable PAYG';end if;
 end if;
 if w.balance_micro_usd<p_reserve-included then raise exception 'Insufficient credit for this action';end if;
 if included>0 then update public.billing_subscriptions set remaining_micro_usd=remaining_micro_usd-included where id=s.id;end if;
 update public.organization_wallets set balance_micro_usd=balance_micro_usd-(p_reserve-included),updated_at=now() where organization_id=p_org;
 insert into public.ai_billing_requests(organization_id,actor_id,ticket_id,operation,request_key,fingerprint,reserved_micro_usd,wallet_reserved,plan_reserved,subscription_id)
 values(p_org,p_actor,p_ticket,p_operation,p_key,p_fingerprint,p_reserve,p_reserve-included,included,s.id) returning * into r;
 return to_jsonb(r)||jsonb_build_object('claimed',true);
end $$;


