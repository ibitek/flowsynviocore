create table if not exists public.flow_bots(
 id uuid primary key default gen_random_uuid(), organization_id uuid not null references public.organizations(id),
 created_by uuid not null references auth.users(id), name text not null default 'My assistant',
 draft jsonb not null default '{}'::jsonb, live jsonb, published boolean not null default false,
 connected boolean not null default false, revision integer not null default 1,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.flow_keys(
 id uuid primary key default gen_random_uuid(), bot_id uuid not null references public.flow_bots(id),
 key_hash text not null unique, prefix text not null, name text not null,
 created_at timestamptz not null default now(), revoked_at timestamptz
);
create table if not exists public.flow_conversations(
 id uuid primary key default gen_random_uuid(), number bigint generated by default as identity(start with 10000000),
 bot_id uuid not null references public.flow_bots(id), secret_hash text not null, origin text not null,
 preview boolean not null default false, state text not null default 'ai' check(state in ('ai','waiting','human','resolved')),
 pending_key text, created_at timestamptz not null default now(), expires_at timestamptz not null default now()+interval '24 hours'
);
create table if not exists public.flow_messages(
 id uuid primary key default gen_random_uuid(), conversation_id uuid not null references public.flow_conversations(id),
 role text not null check(role in ('user','assistant','agent','system')), content text not null,
 request_key text not null, created_at timestamptz not null default now(), unique(conversation_id,request_key,role)
);
create table if not exists public.flow_jobs(
 conversation_id uuid not null references public.flow_conversations(id), request_key text not null,
 user_text text not null, config jsonb not null, history jsonb not null,
 result jsonb, primary key(conversation_id,request_key)
);
create table if not exists public.flow_limits(bucket text primary key, hits integer not null, expires_at timestamptz not null);
create index if not exists flow_conversations_bot_idx on public.flow_conversations(bot_id,created_at desc);
create index if not exists flow_messages_chat_idx on public.flow_messages(conversation_id,created_at);
-- All data is served by authenticated, organization-scoped endpoints. No direct browser table writes.
