create or replace function public.flow_rate(p_bucket text,p_max integer,p_seconds integer) returns boolean
language plpgsql security definer set search_path='' as $$
declare n integer;
begin
 insert into public.flow_limits(bucket,hits,expires_at) values(p_bucket,1,now()+make_interval(secs=>p_seconds))
 on conflict(bucket) do update set hits=case when public.flow_limits.expires_at<now() then 1 else public.flow_limits.hits+1 end,
 expires_at=case when public.flow_limits.expires_at<now() then now()+make_interval(secs=>p_seconds) else public.flow_limits.expires_at end returning hits into n;
 return n<=p_max;
end $$;

create or replace function public.flow_begin(p_conversation uuid,p_key text,p_text text,p_page text default '') returns jsonb
language plpgsql security definer set search_path='' as $$
declare c public.flow_conversations%rowtype; b public.flow_bots%rowtype; j public.flow_jobs%rowtype; cfg jsonb; h jsonb;
begin
 select * into c from public.flow_conversations where id=p_conversation for update;
 if not found or c.expires_at<now() or c.state='resolved' then raise exception 'Conversation expired or resolved'; end if;
 select * into j from public.flow_jobs where conversation_id=c.id and request_key=p_key;
 if found then
  if j.user_text<>p_text then raise exception 'Request ID reused for different text';end if;
  return to_jsonb(j);
 end if;
 if c.pending_key is not null then raise exception 'Previous request pending. Retry its request ID.';end if;
 if (select count(*) from public.flow_messages where conversation_id=c.id)>=400 then raise exception 'Conversation limit reached. Start a new chat.';end if;
 select * into b from public.flow_bots where id=c.bot_id;
 cfg=case when c.preview then b.draft else b.live end;
 cfg=jsonb_set(cfg,'{pageContext}',to_jsonb(left(p_page,2000)));
 if c.state in ('waiting','human') then cfg=jsonb_set(cfg,'{mode}','"human"');end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at),'[]') into h from
 (select role,content,created_at from public.flow_messages where conversation_id=c.id order by created_at desc,id desc limit 8) x;
 insert into public.flow_jobs values(c.id,p_key,p_text,cfg,h,null) returning * into j;
 insert into public.flow_messages(conversation_id,role,content,request_key) values(c.id,'user',p_text,p_key);
 update public.flow_conversations set pending_key=p_key where id=c.id;
 return to_jsonb(j);
end $$;

create or replace function public.flow_finish(p_conversation uuid,p_key text,p_result jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare j public.flow_jobs%rowtype;
begin
 perform 1 from public.flow_conversations where id=p_conversation for update;
 select * into j from public.flow_jobs where conversation_id=p_conversation and request_key=p_key for update;
 if not found then raise exception 'Request missing';end if;
 if j.result is not null then return j.result;end if;
 if coalesce(p_result->>'reply','')<>'' then
 insert into public.flow_messages(conversation_id,role,content,request_key) values(p_conversation,'assistant',p_result->>'reply',p_key) on conflict do nothing;
 end if;
 update public.flow_jobs set result=p_result where conversation_id=p_conversation and request_key=p_key;
 update public.flow_conversations set pending_key=null where id=p_conversation and pending_key=p_key;
 return p_result;
end $$;

create or replace function public.flow_open(p_bot uuid,p_secret text,p_origin text,p_preview boolean) returns jsonb
language plpgsql security definer set search_path='' as $$
declare b public.flow_bots%rowtype;cfg jsonb;c public.flow_conversations%rowtype;
begin
 select * into b from public.flow_bots where id=p_bot for update;
 if not found or (not p_preview and not b.published) then raise exception 'Assistant offline';end if;
 cfg=case when p_preview then b.draft else b.live end;
 if cfg->>'mode'<>'ai' and not b.connected then raise exception 'Workspace disconnected';end if;
 insert into public.flow_conversations(bot_id,secret_hash,origin,preview,state)
 values(b.id,p_secret,p_origin,p_preview,case when cfg->>'mode'='human' then 'waiting' else 'ai' end) returning * into c;
 return jsonb_build_object('id',c.id,'number',c.number);
end $$;
create or replace function public.flow_connect(p_bot uuid,p_org uuid,p_revision integer,p_connected boolean) returns jsonb
language plpgsql security definer set search_path='' as $$
declare b public.flow_bots%rowtype;
begin
 select * into b from public.flow_bots where id=p_bot and organization_id=p_org for update;
 if not found or b.revision<>p_revision then raise exception 'Settings changed. Reload.';end if;
 if not p_connected and exists(select 1 from public.flow_conversations where bot_id=p_bot and state in ('waiting','human')) then raise exception 'Resolve open human conversations before disconnecting.';end if;
 update public.flow_bots set connected=p_connected,revision=revision+1,updated_at=now(),
 draft=case when p_connected then draft else jsonb_set(draft,'{mode}','"ai"') end,
 live=case when p_connected or live is null then live else jsonb_set(live,'{mode}','"ai"') end where id=p_bot returning * into b;
 return to_jsonb(b);
end $$;
create or replace function public.flow_handoff(p_conversation uuid,p_key text default '') returns void
language plpgsql security definer set search_path='' as $$
declare c public.flow_conversations%rowtype;b public.flow_bots%rowtype;
begin
 select * into c from public.flow_conversations where id=p_conversation for update;
 select * into b from public.flow_bots where id=c.bot_id for update;
 if not b.connected or c.state='resolved' or (c.pending_key is not null and c.pending_key is distinct from p_key) then raise exception 'Handoff unavailable or reply pending';end if;
 update public.flow_conversations set state='waiting' where id=c.id and state='ai';
end $$;
create or replace function public.flow_team_action(p_conversation uuid,p_org uuid,p_actor uuid,p_text text,p_key text,p_resolve boolean) returns void
language plpgsql security definer set search_path='' as $$
declare c public.flow_conversations%rowtype;b public.flow_bots%rowtype;prior text;
begin
 select * into c from public.flow_conversations where id=p_conversation for update;
 select * into b from public.flow_bots where id=c.bot_id;
 if b.organization_id is distinct from p_org or not exists(select 1 from public.organization_members where organization_id=p_org and user_id=p_actor) then raise exception 'Access denied';end if;
 if c.pending_key is not null then raise exception 'Reply pending';end if;
 if p_resolve then update public.flow_conversations set state='resolved' where id=c.id;return;end if;
 select content into prior from public.flow_messages where conversation_id=c.id and request_key=p_key and role='agent';
 if found then if prior<>p_text then raise exception 'Request ID reused with different text';end if;return;end if;
 if not b.connected or c.state not in ('waiting','human') or c.expires_at<now() then raise exception 'Conversation unavailable';end if;
 insert into public.flow_messages(conversation_id,role,content,request_key) values(c.id,'agent',p_text,p_key);
 update public.flow_conversations set state='human' where id=c.id;
end $$;
